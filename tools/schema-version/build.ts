// OPS-05 (audit 2026-10-18): writes apps/web/src/server/schema-version.generated.ts with the
// version of the newest file in supabase/migrations. The web build runs this before `next build`,
// so the deployed code carries the schema it expects; build.test.ts fails when the committed file
// is out of date (run `pnpm schema:version` after adding a migration).
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
export const OUTPUT = "apps/web/src/server/schema-version.generated.ts";
const MIGRATIONS = "supabase/migrations";

/** Supabase names migrations "<14-digit UTC timestamp>_<name>.sql"; the version is the digits. */
export function newestMigrationVersion(files: readonly string[]): string {
  const versions = files
    .map((file) => /^(\d{14})_[a-z0-9_]+\.sql$/.exec(file)?.[1])
    .filter((version): version is string => version !== undefined)
    .sort();
  const newest = versions.at(-1);
  if (newest === undefined) throw new Error(`${MIGRATIONS}: no migration file found`);
  return newest;
}

export function buildSchemaVersionModule(
  files: readonly string[] = readdirSync(join(ROOT, MIGRATIONS)),
): string {
  return `// Generated by tools/schema-version/build.ts from supabase/migrations. Do not edit; run
// \`pnpm schema:version\`. OPS-05: the newest migration this code was built against.
export const EXPECTED_SCHEMA_VERSION = ${JSON.stringify(newestMigrationVersion(files))};
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  writeFileSync(join(ROOT, OUTPUT), buildSchemaVersionModule());
  console.log(`Wrote ${OUTPUT}`);
}
