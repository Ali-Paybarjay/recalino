"""Patch native RTL metadata in an Artifact Tool-authored PPTX.

Uses only Python's standard library. It never reverses text, rasterizes text,
or changes geometry. Input and output must be distinct files.
"""
from __future__ import annotations

import argparse
import io
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

A = "http://schemas.openxmlformats.org/drawingml/2006/main"
P = "http://schemas.openxmlformats.org/presentationml/2006/main"
ARABIC = re.compile(r"[\u0600-\u06ff\u0750-\u077f\u08a0-\u08ff\ufb50-\ufdff\ufe70-\ufeff]")
NS = {"a": A, "p": P}


def tag(local: str) -> str:
    return f"{{{A}}}{local}"


def register_original_namespaces(data: bytes) -> None:
    for _, (prefix, uri) in ET.iterparse(io.BytesIO(data), events=("start-ns",)):
        # ElementTree reserves autogenerated ns<number> names.
        if not re.fullmatch(r"ns\d+", prefix):
            ET.register_namespace(prefix, uri)


def ensure_cs(properties: ET.Element, fallback_family: str) -> None:
    latin = properties.find(tag("latin"))
    family = latin.get("typeface") if latin is not None else fallback_family
    cs = properties.find(tag("cs"))
    if cs is None:
        cs = ET.Element(tag("cs"))
        # CT_TextCharacterProperties: latin, ea, cs, sym, hyperlinks, extLst.
        successors = {tag(x) for x in ("sym", "hlinkClick", "hlinkMouseOver", "extLst")}
        index = next((i for i, child in enumerate(properties) if child.tag in successors), len(properties))
        properties.insert(index, cs)
    cs.set("typeface", family or fallback_family)
    properties.set("lang", "fa-IR")


def ensure_child_first(parent: ET.Element, name: str) -> ET.Element:
    child = parent.find(tag(name))
    if child is None:
        child = ET.Element(tag(name))
        parent.insert(0, child)
    return child


def patch_xml(data: bytes, fallback_family: str) -> tuple[bytes, dict[str, int]]:
    register_original_namespaces(data)
    root = ET.fromstring(data)
    counts = {"paragraphs": 0, "runs": 0}
    # Each paragraph remains editable. Latin-only paragraphs retain their direction.
    for para in root.findall(".//a:p", NS):
        para_text = "".join(para.itertext())
        if not ARABIC.search(para_text):
            continue
        ppr = ensure_child_first(para, "pPr")
        ppr.set("rtl", "1")
        defaults = ppr.find(tag("defRPr"))
        if defaults is None:
            defaults = ET.Element(tag("defRPr"))
            extension = ppr.find(tag("extLst"))
            ppr.insert(list(ppr).index(extension) if extension is not None else len(ppr), defaults)
        ensure_cs(defaults, fallback_family)
        for run in para.findall(tag("r")) + para.findall(tag("fld")):
            text = "".join(node.text or "" for node in run.findall(tag("t")))
            if ARABIC.search(text):
                rpr = ensure_child_first(run, "rPr")
                ensure_cs(rpr, fallback_family)
                counts["runs"] += 1
        end = para.find(tag("endParaRPr"))
        if end is not None:
            ensure_cs(end, fallback_family)
        counts["paragraphs"] += 1
    if not counts["paragraphs"]:
        return data, counts
    return ET.tostring(root, encoding="utf-8", xml_declaration=True), counts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--font", default="Segoe UI")
    args = parser.parse_args()
    source = args.source.resolve(strict=True)
    output = args.output.resolve()
    if source == output:
        parser.error("Input and output must be distinct paths.")
    if output.exists():
        parser.error("Output already exists. Choose a new filename.")
    output.parent.mkdir(parents=True, exist_ok=True)
    report: dict[str, object] = {"source": str(source), "output": str(output), "files": [], "paragraphs": 0, "runs": 0}
    with zipfile.ZipFile(source, "r") as incoming, zipfile.ZipFile(output, "x") as outgoing:
        for info in incoming.infolist():
            data = incoming.read(info.filename)
            # Slide-local text only. Master/layout/notes remain byte-identical.
            if re.fullmatch(r"ppt/slides/slide\d+\.xml", info.filename):
                data, counts = patch_xml(data, args.font)
                if counts["paragraphs"]:
                    report["files"].append({"name": info.filename, **counts})
                    report["paragraphs"] += counts["paragraphs"]
                    report["runs"] += counts["runs"]
            outgoing.writestr(info, data)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
