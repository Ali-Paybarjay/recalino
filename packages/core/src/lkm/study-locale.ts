export interface StudyLocale {
  language: string;
  direction: "ltr" | "rtl" | "auto";
  isPersian: boolean;
  fontFamily: string;
}

export function resolveStudyLocale(language: string): StudyLocale {
  let canonical = "en";
  try {
    canonical = Intl.getCanonicalLocales(language)[0] ?? "en";
  } catch {
    // Hostile or stale persisted locale strings cannot become markup or CSS.
  }
  const base = canonical.split("-")[0] ?? "en";
  const script = canonical.split("-").find((part) => /^[A-Z][a-z]{3}$/.test(part));
  const direction = script
    ? ["Arab", "Hebr", "Thaa", "Adlm", "Nkoo"].includes(script)
      ? "rtl"
      : "ltr"
    : ambiguousScripts.has(base)
      ? "auto"
      : rtlLanguages.has(base)
        ? "rtl"
        : "ltr";
  const fontKey = canonical.startsWith("zh")
    ? canonical.includes("Hant") || /-(?:TW|HK|MO)\b/.test(canonical)
      ? "zh-Hant"
      : "zh-Hans"
    : base;
  const explicitScriptFont: Record<string, string> = {
    Arab: "ar",
    Hebr: "he",
    Thaa: "dv",
    Deva: "hi",
    Guru: "pa-Guru",
    Beng: "bn",
    Gujr: "gu",
    Knda: "kn",
    Mlym: "ml",
    Orya: "or",
    Taml: "ta",
    Telu: "te",
    Sinh: "si",
    Thai: "th",
    Laoo: "lo",
    Khmr: "km",
    Mymr: "my",
    Tibt: "bo",
    Ethi: "am",
    Armn: "hy",
    Geor: "ka",
    Hang: "ko",
    Jpan: "ja",
    Hans: "zh-Hans",
    Hant: "zh-Hant",
  };
  const fontFamily =
    fontProfiles[(script && explicitScriptFont[script]) || fontKey] ??
    '"Noto Sans", Arial, Tahoma, sans-serif';
  return {
    language: canonical,
    direction,
    isPersian: base === "fa",
    fontFamily,
  };
}
function translationKey(locale: StudyLocale): string {
  return locale.language.startsWith("zh")
    ? locale.language.includes("Hant") || /-(?:TW|HK|MO)\b/.test(locale.language)
      ? "zh-Hant"
      : "zh-Hans"
    : (locale.language.split("-")[0] ?? "en");
}
export function studyMessage(
  language: string,
  key: StudyLabelKey,
): { text: string; language: string } {
  const locale = resolveStudyLocale(language);
  const translated = translations[translationKey(locale)]?.[key];
  return {
    text: translated ?? ENGLISH_STUDY_LABELS[key],
    language: translated ? locale.language : "en",
  };
}
export function studyText(language: string, key: StudyLabelKey): string {
  return studyMessage(language, key).text;
}
/** Localized homework heading markers; English markers are recognised for every language. */
export function studyHomeworkMarkers(language: string): {
  labels: readonly string[];
  negators: readonly string[];
  unspaced: boolean;
} {
  const key = translationKey(resolveStudyLocale(language));
  const markers = homeworkMarkers[key];
  return {
    labels: markers?.labels ?? [],
    negators: markers?.negators ?? [],
    unspaced: unspacedHomeworkMarkers.has(key),
  };
}
export function studyNumber(value: number, language: string): string {
  const locale = resolveStudyLocale(language);
  return new Intl.NumberFormat(locale.language, { useGrouping: false }).format(value);
}
export function studyWeekday(date: Date, language: string): string {
  return new Intl.DateTimeFormat(resolveStudyLocale(language).language, {
    weekday: "long",
    timeZone: "UTC",
  }).format(date);
}
