const sentence = "I have studied English for two years.";
let stage = "configuration";
function safeCode(error: unknown): string {
  return error instanceof AppError || error instanceof ProviderError
    ? error.code
    : error instanceof Error && /^[a-z][a-z0-9_]{0,80}$/.test(error.message)
      ? error.message
      : "synthetic_evaluation_failed";
}
function argument(name: string) {
  const at = process.argv.indexOf(name);
  if (at === -1) return undefined;
  const value = process.argv[at + 1];
  if (!value || value.startsWith("--")) throw new Error("missing_argument");
  return value;
}
/** A second, independent ceiling includes ambiguous attempts and retries; it never refunds calls. */
function boundedProvider(base: AiProvider, maximumTotalMicros: number) {
  let attemptedBoundMicros = 0;
  let attemptedCalls = 0;
  const claim = (model: string) => {
    const bound = maximumProviderCost(base.settings, model);
    if (attemptedCalls >= 4 || attemptedBoundMicros + bound > maximumTotalMicros)
      throw new ProviderError("evaluation_budget_exhausted", false, false);
    attemptedCalls++;
    attemptedBoundMicros += bound;
  };
  const provider: AiProvider = {
    name: base.name,
    mode: base.mode,
    settings: base.settings,
    async structured(input) {
      claim(input.model);
      return base.structured(input);
    },
    async transcribe(input) {
      claim(input.model);
      return base.transcribe(input);
    },
    async speech(input) {
      claim(input.model ?? base.settings.ttsModel);
      return base.speech(input);
    },
  };
  return { provider, stats: () => ({ attemptedCalls, attemptedBoundMicros }) };
}
/** Bytes are generated by TTS from the fixed sentence above, never supplied by a learner. */
async function syntheticAudioDuration(bytes: Uint8Array): Promise<number> {
  if (!ffmpeg || bytes.length > 5 * 1024 * 1024) throw new Error("synthetic_audio_invalid");
  const executable = ffmpeg;
  const directory = await mkdtemp(join(tmpdir(), "recalino-synthetic-eval-"));
  try {
    const path = join(directory, "synthetic.mp3");
    await writeFile(path, bytes);
    let diagnostic = "";
    await new Promise<void>((ok, fail) => {
      const child = spawn(executable, ["-nostdin", "-hide_banner", "-i", path, "-f", "null", "-"], {
        windowsHide: true,
        stdio: ["ignore", "ignore", "pipe"],
      });
      const timer = setTimeout(() => {
        child.kill();
        fail(new Error("synthetic_audio_timeout"));
      }, 15000);
      child.stderr.on("data", (chunk: Buffer) => {
        diagnostic = (diagnostic + chunk.toString()).slice(-64000);
      });
      child.on("error", () => {
        clearTimeout(timer);
        fail(new Error("synthetic_audio_decoder_unavailable"));
      });
      child.on("exit", (code) => {
        clearTimeout(timer);
        code === 0 ? ok() : fail(new Error("synthetic_audio_decode_failed"));
      });
    });
    const match = /Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)/.exec(diagnostic);
    const duration = match
      ? Math.ceil((Number(match[1]) * 3600 + Number(match[2]) * 60 + Number(match[3])) * 1000)
      : 0;
    if (!duration || duration > 60000) throw new Error("synthetic_audio_duration_invalid");
    return duration;
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

async function main() {
  if (process.argv.includes("--help")) {
    process.stdout.write(
      "Usage: pnpm --filter @recalino/ops-cli evaluate --config path [--env path] [--real] [--class-only] [--report path]\nLocal Supabase and generated synthetic input only. Real calls require explicit --real and a <=100000 USD-micro total ceiling.\n",
    );
    return;
  }
  const envFile = argument("--env");
  if (envFile) process.loadEnvFile(workspacePath(envFile));
  const configFile = argument("--config");
  if (!configFile) throw new Error("evaluation_config_required");
  const bytes = await readFile(workspacePath(configFile));
  if (bytes.length > 65536) throw new Error("evaluation_config_too_large");
  const config = evaluationConfigSchema.parse(JSON.parse(bytes.toString("utf8")));
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error("database_url_required");
  assertLocalEvaluationDatabase(connectionString);
  const real = process.argv.includes("--real");
  const providerKey = process.env.OPENROUTER_API_KEY;
  if (real && !providerKey) throw new Error("openrouter_key_required");
  if (!config.provider.dataContractApproved) throw new Error("provider_data_contract_required");
  const providerDiagnostics: { status: number; message: string }[] = [];
  const diagnosticFetch: typeof fetch = async (input, init) => {
    const response = await fetch(input, init);
    if (response.status === 400 && process.argv.includes("--debug-provider")) {
      const raw: unknown = await response
        .clone()
        .json()
        .catch(() => null);
      const envelope = z
        .object({
          error: z.object({
            message: z.string().optional(),
            metadata: z.object({ raw: z.string().optional() }).optional(),
          }),
        })
        .safeParse(raw);
      if (envelope.success) {
        let message = envelope.data.error.message ?? "provider_request_invalid";
        const native = envelope.data.error.metadata?.raw;
        if (native) {
          const parsed: unknown = (() => {
            try {
              return JSON.parse(native);
            } catch {
              return null;
            }
          })();
          const detail = z.object({ error: z.object({ message: z.string() }) }).safeParse(parsed);
          if (detail.success) message = detail.data.error.message;
        }
        // This flag exists only in the local synthetic harness. Never record request/headers/schema.
        message = message
          .replaceAll(providerKey ?? "never-a-key", "[redacted]")
          .replace(/https?:\/\/\S+/g, "[url]")
          .replace(/Bearer\s+\S+/gi, "[redacted]")
          .slice(0, 1200);
        providerDiagnostics.push({ status: response.status, message });
      }
    }
    return response;
  };
  const base: AiProvider = real
    ? new OpenRouterProvider(providerKey ?? "", config.provider, diagnosticFetch)
    : new SyntheticEvaluationProvider(config.provider);
  const bounded = boundedProvider(base, config.maximumTotalMicros);
  const provider = bounded.provider;
  const db = createDatabase(connectionString, { maxConnections: 3 });
  const started = new Date();
  const now = () => new Date();
  try {
    stage = "local_cost_policy";
    await configureCostPolicy(
      db,
      {
        version: config.version,
        currency: "USD",
        killSwitch: false,
        limits: {
          session: config.maximumTotalMicros,
          userMonth: config.maximumTotalMicros,
          systemDay: config.maximumTotalMicros,
          systemMonth: config.maximumTotalMicros,
        },
      },
      { actorId: config.actorId, reason: config.reason },
    );
    stage = "synthetic_account";
    const userId = await createAuthUser();
    const ctx = { userId, requestId: randomUUID() };
    const intent = await createSignupIntent(db, {
      versions: CURRENT_VERSIONS,
      ttlSeconds: 600,
      now: now(),
    });
    await completeSignIn(db, { userId, intentId: intent.id, now: now() });
    for (const change of [
      { field: "first_language", firstLanguage: "fa" },
      { field: "explanation_language", explanationLanguage: "english" },
      { field: "level_goal", level: null, goal: null },
      { field: "timezone", timezone: "Europe/London" },
    ] as const)
      await updateProfile(db, ctx, change, { now: now() });
    await acceptDocuments(
      db,
      ctx,
      [{ document: "recording-consent", version: CURRENT_VERSIONS["recording-consent"] }],
      { now: now() },
    );
    const session = await createSession(db, ctx, {}, { key: randomUUID() });
    await grantEntitlement(db, {
      userId,
      startsAt: new Date(started.getTime() - 1000),
      endsAt: new Date(started.getTime() + 3600000),
      amounts: amounts({
        document: 5,
        audio: 60,
        tts: 500,
        regeneration: 5,
        storage: 10 * 1024 * 1024,
      }),
      operationKey: randomUUID(),
      actorId: config.actorId,
      reason: "Synthetic local evaluation only",
    });
    stage = "synthetic_source";
    const store = new MemoryObjectStore();
    const contract = await readInputContract(db);
    await acceptSourceNotice(db, ctx, contract.noticeVersion, true);
    const input = Buffer.from(
      "Present perfect: have/has + past participle. I have studied English for two years. The action started in the past and continues now. Contrast: I studied English yesterday, which describes a finished past time.",
    );
    const hash = createHash("sha256").update(input).digest("hex");
    const source = await createSource(db, ctx, {
      sessionId: session.id,
      kind: "text",
      mimeType: "text/plain",
      sizeBytes: input.length,
      sha256: hash,
      displayName: "Synthetic English lesson.txt",
      parts: [{ index: 0, sizeBytes: input.length, sha256: hash }],
      operationKey: randomUUID(),
    });
    if (!source.uploadId) throw new Error("synthetic_upload_missing");
    const link = await uploadPartLink(
      db,
      store,
      ctx,
      source.uploadId,
      0,
      readPltSettings().storage,
    );
    if (store.upload(link.url, input, "text/plain") !== 200)
      throw new Error("synthetic_upload_failed");
    await confirmUploadPart(db, store, ctx, source.uploadId, 0);
    const uploaded = await verifyUpload(db, store, ctx, source.uploadId);
    if (uploaded.state !== "verified") throw new Error("synthetic_source_verification_failed");
    const extractedVersions = await sourceContentVersions(db, ctx, source.assetId);
    const selectedVersion = extractedVersions[0];
    if (!selectedVersion) throw new Error("synthetic_extraction_missing");
    await updateSourceSelection(db, ctx, session.id, source.assetId, {
      selected: true,
      ranges: [],
      role: "class_material",
      timeStatus: "unknown",
      contentVersionId: selectedVersion.id,
    });
    const snapshot = sourceSnapshotSchema.parse(await selectSourceSnapshot(db, ctx, session.id));
    stage = "class_processing";
    const job = processingJob({ provider, store });
    const run = await createProcessingRun(
      db,
      ctx,
      {
        sessionId: session.id,
        operationKey: randomUUID(),
        expectedFingerprint: snapshot.fingerprint,
        expectedSourcesVersion: snapshot.sourcesVersion,
      },
      { provider, job },
    );
    await runDueJobs(db, [job], {
      kinds: [job.kind],
      deadline: new Date(Date.now() + provider.settings.timeoutMs + 10000),
    });
    const result = await getRun(db, ctx, run.id);
    const knowledge = result.state === "ready" ? await getLatestVersion(db, ctx, session.id) : null;
    const quality = knowledge
      ? structuralQualityReport(
          knowledge.model,
          snapshot.sources.filter((item): item is typeof item & { contentVersionId: string } =>
            Boolean(item.contentVersionId),
          ),
          "en",
        )
      : null;
    let study: { notebookPublished: boolean; proposedCards: number } | null = null;
    if (knowledge) {
      await publishNotebook(
        db,
        ctx,
        session.id,
        { expectedRevisionId: null },
        { key: randomUUID() },
      );
      const cards = await generateCards(
        db,
        ctx,
        session.id,
        { autoAdd: false },
        { key: randomUUID() },
      );
      study = { notebookPublished: true, proposedCards: cards.cards.length };
    }
    if (process.argv.includes("--class-only")) {
      const report = {
        schemaVersion: "1",
        configVersion: config.version,
        scope: "class-only",
        mode: provider.mode,
        syntheticOnly: true,
        localOnly: true,
        startedAt: started.toISOString(),
        finishedAt: now().toISOString(),
        maximumTotalMicros: config.maximumTotalMicros,
        ...bounded.stats(),
        model: provider.settings.llmModel,
        priceVersion: provider.settings.priceVersion,
        classProcessing: {
          runId: run.id,
          state: result.state,
          error: result.lastError,
          quality,
          study,
        },
        costs: await providerCostSummary(db, started),
        providerDiagnostics,
        humanReview: "required",
      };
      const reportFile = argument("--report");
      if (reportFile)
        await writeFile(workspacePath(reportFile), `${JSON.stringify(report, null, 2)}\n`);
      process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
      if (result.state !== "ready") process.exitCode = 1;
      return;
    }
    stage = "synthetic_vision";
    const canvas = createCanvas(1000, 180);
    const context = canvas.getContext("2d");
    context.fillStyle = "white";
    context.fillRect(0, 0, 1000, 180);
    context.fillStyle = "black";
    context.font = "32px sans-serif";
    context.fillText(sentence, 35, 95);
    const vision = await evaluateAuxiliaryProvider(db, ctx, session.id, provider, {
      kind: "vision",
      bytes: canvas.toBuffer("image/png"),
      mimeType: "image/png",
    });
    stage = "synthetic_tts";
    const media: MediaDependencies = {
      provider,
      store,
      settings: { maxTtsCharacters: 500, maxTtsBytes: 5 * 1024 * 1024 },
      processor: {
        schedule: scheduleAuxiliaryRun,
        execute: executeAuxiliaryProviderStep,
        complete: completeAuxiliaryRun,
        fail: failAuxiliaryRun,
      },
    };
    const speech = await requestTts(
      db,
      ctx,
      { sessionId: session.id, text: sentence, operationKey: randomUUID(), exportAllowed: false },
      media,
    );
    const speechJob = mediaTtsJob(media);
    await runDueJobs(db, [speechJob], {
      kinds: [speechJob.kind],
      deadline: new Date(Date.now() + provider.settings.timeoutMs + 10000),
    });
    const speechAsset = await getMediaAsset(db, ctx, speech.id);
    let transcription: Awaited<ReturnType<typeof evaluateAuxiliaryProvider>> | null = null;
    stage = "synthetic_transcription";
    if (speechAsset.state === "ready") {
      const audio = await readMediaBytes(db, store, ctx, speech.id);
      transcription = await evaluateAuxiliaryProvider(db, ctx, session.id, provider, {
        kind: "transcription",
        bytes: audio.bytes,
        format: "mp3",
        durationMs: real ? await syntheticAudioDuration(audio.bytes) : 1000,
      });
    }
    const costs = await providerCostSummary(db, started);
    const report = {
      schemaVersion: "1",
      configVersion: config.version,
      mode: provider.mode,
      syntheticOnly: true,
      localOnly: true,
      startedAt: started.toISOString(),
      finishedAt: now().toISOString(),
      maximumTotalMicros: config.maximumTotalMicros,
      ...bounded.stats(),
      models: {
        llm: provider.settings.llmModel,
        vision: provider.settings.visionModel,
        stt: provider.settings.sttModel,
        tts: provider.settings.ttsModel,
      },
      priceVersion: provider.settings.priceVersion,
      classProcessing: {
        runId: run.id,
        state: result.state,
        error: result.lastError,
        quality,
        study,
      },
      vision,
      tts: { state: speechAsset.state, error: speechAsset.lastError },
      transcription,
      costs,
      corpus: {
        version: "synthetic-plan-1",
        plannedCases: evaluationCorpus.length,
        completedHumanReviews: 0,
      },
      humanReview: "required",
    };
    stage = "metadata_report";
    const reportFile = argument("--report");
    if (reportFile)
      await writeFile(workspacePath(reportFile), `${JSON.stringify(report, null, 2)}\n`);
    process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
    if (
      result.state !== "ready" ||
      vision.state !== "ready" ||
      speechAsset.state !== "ready" ||
      transcription?.state !== "ready"
    )
      process.exitCode = 1;
  } finally {
    await db.destroy();
  }
}
main().catch((error: unknown) => {
  const diagnostic =
    error instanceof z.ZodError
      ? {
          kind: "schema",
          issues: error.issues.map((issue) => ({ code: issue.code, path: issue.path })),
        }
      : error instanceof Error
        ? {
            kind: error.name,
            location: error.stack
              ?.split("\n")
              .filter((line) => /^\s+at /.test(line))
              .slice(0, 3)
              .map((line) => line.trim()),
          }
        : null;
  process.stderr.write(`${JSON.stringify({ stage, error: safeCode(error), diagnostic })}\n`);
  process.exitCode = 1;
});
